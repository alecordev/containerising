#!/usr/bin/env python3
# /// script
# requires-python = ">=3.10"
# dependencies = []
# ///

"""Make every Python example work with uv, with requirements.txt as the single source of truth.

For each *uv project* directory (one with a generated ``pyproject.toml``) this tool writes:

* ``pyproject.toml``: ``dependencies`` copied from ``requirements.txt`` (``uv sync`` / ``uv run python x.py``),
* a PEP 723 inline-metadata block at the top of every example ``.py`` under that directory
  (``uv run path/to/x.py`` works from anywhere with no setup, dependencies installed on the fly).

``requirements.txt`` stays (legacy ``pip install -r``, Docker builds) and is the only file you edit.
It also adds/refreshes PEP 723 blocks for the repo's stdlib-only tools (``STDLIB_SCRIPTS``) and for every service
``smoke*.py`` so ``uv run`` picks a suitable Python automatically (and does not sync a neighbouring uv project).

Python 3.10+ standard library only. Usage:

    python scripts/sync_uv.py               # write pyproject.toml + script headers for every project
    python scripts/sync_uv.py --check       # exit 1 if anything is out of date (used by scripts/lint.py)
    python scripts/sync_uv.py --add DIR     # register DIR (must contain requirements.txt) as a uv project
    python scripts/sync_uv.py --lock        # also run `uv lock` in each project (needs uv and network)
    python scripts/sync_uv.py --list
"""
from __future__ import annotations

import json
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MARKER = "# Generated by scripts/sync_uv.py from requirements.txt. Edit requirements.txt, then run: python scripts/sync_uv.py"
SKIP_DIRS = {".git", ".venv", "venv", "node_modules", "__pycache__", "data", "output"}
DEFAULT_REQUIRES_PYTHON = ">=3.11"   # examples: some current client libraries (pymongo 4.19+) need 3.11
TOOLS_REQUIRES_PYTHON = ">=3.10"     # the stdlib-only repo tools
# Stdlib-only tools that get a PEP 723 block (no dependencies) so `uv run` selects a suitable Python.
STDLIB_SCRIPTS = [
    "scripts/smoke.py", "scripts/lint.py", "scripts/sync_uv.py", "scripts/ports.py", "scripts/new_service.py", "wikipedia/prep/wiki.py",
]
PEP723 = re.compile(r"(?m)^# /// script\r?\n(?:#(?: .*)?\r?\n)*?# ///\r?\n")


# --------------------------------------------------------------------------- requirements
def read_requirements(path: Path, seen: set[Path] | None = None) -> list[str]:
    """Requirement lines of a requirements.txt (follows ``-r``), comments stripped, order kept, de-duplicated."""
    seen = seen or set()
    path = path.resolve()
    if path in seen or not path.exists():
        return []
    seen.add(path)
    out: list[str] = []
    for raw in path.read_text(encoding="utf-8").splitlines():
        line = re.sub(r"\s+#.*$", "", raw).strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith(("-r ", "--requirement ")):
            out += read_requirements(path.parent / line.split(None, 1)[1].strip(), seen)
        elif line.startswith("-"):
            print(f"warning: {path.relative_to(ROOT)}: option line ignored: {line}", file=sys.stderr)
        else:
            out.append(line)
    return list(dict.fromkeys(out))


def toml_str(s: str) -> str:
    return json.dumps(s)  # JSON strings are valid TOML basic strings


# --------------------------------------------------------------------------- generated content
def project_name(d: Path) -> str:
    rel = d.relative_to(ROOT).as_posix()
    return "containerising-" + re.sub(r"[^a-z0-9]+", "-", rel.lower()).strip("-")


def existing_requires_python(pyproject: Path) -> str:
    if pyproject.exists():
        m = re.search(r'(?m)^requires-python\s*=\s*"([^"]+)"', pyproject.read_text(encoding="utf-8"))
        if m:
            return m.group(1)
    return DEFAULT_REQUIRES_PYTHON


def render_pyproject(d: Path) -> str:
    deps = read_requirements(d / "requirements.txt")
    rp = existing_requires_python(d / "pyproject.toml")
    dep_lines = "".join(f"    {toml_str(x)},\n" for x in deps)
    return (
        f"{MARKER}\n"
        "# (requires-python and anything below it may be edited by hand; dependencies are overwritten.)\n"
        "[project]\n"
        f"name = {toml_str(project_name(d))}\n"
        'version = "0.0.0"\n'
        f"description = {toml_str('Example scripts: ' + d.relative_to(ROOT).as_posix())}\n"
        f'requires-python = "{rp}"\n'
        f"dependencies = [\n{dep_lines}]\n"
        "\n"
        "[tool.uv]\n"
        "package = false  # scripts, not an installable package\n"
    )


def header_block(deps: list[str], requires_python: str) -> str:
    lines = ["# /// script", f'# requires-python = "{requires_python}"']
    if deps:
        lines.append("# dependencies = [")
        lines += [f"#     {toml_str(x)}," for x in deps]
        lines.append("# ]")
    else:
        lines.append("# dependencies = []")
    lines.append("# ///")
    return "\n".join(lines) + "\n"


def with_header(text: str, block: str) -> str:
    """Insert/replace the PEP 723 block: after a shebang / coding line, before everything else."""
    text = text.replace("\r\n", "\n")
    text = PEP723.sub("", text, count=1)
    head = ""
    lines = text.split("\n")
    i = 0
    while i < len(lines) and (lines[i].startswith("#!") or re.match(r"#.*coding[:=]", lines[i])):
        i += 1
    head = "\n".join(lines[:i]) + ("\n" if i else "")
    rest = "\n".join(lines[i:]).lstrip("\n")
    return head + block + ("\n" if rest else "") + rest


# --------------------------------------------------------------------------- discovery
def projects() -> list[Path]:
    found = []
    for dp, dn, fn in os.walk(ROOT):
        dn[:] = sorted(x for x in dn if x not in SKIP_DIRS)
        if "pyproject.toml" in fn:
            p = Path(dp) / "pyproject.toml"
            if MARKER.split(".")[0] in p.read_text(encoding="utf-8", errors="replace")[:200]:
                found.append(Path(dp))
    return sorted(found)


def scripts_of(project: Path) -> list[Path]:
    """Example scripts of a project: every .py below it except smoke tests and nested projects/requirements."""
    out = []
    for dp, dn, fn in os.walk(project):
        dpp = Path(dp)
        dn[:] = sorted(
            x for x in dn
            if x not in SKIP_DIRS
            and not any((dpp / x / r).exists() for r in ("requirements.txt", "pyproject.toml"))
        )
        for f in sorted(fn):
            if f.endswith(".py") and not f.startswith("smoke") and f != "conftest.py":
                out.append(dpp / f)
    return out


def smoke_files() -> list[Path]:
    """Every service smoke test (smoke*.py outside scripts/): stdlib only, but they must not pick up a neighbour project."""
    out = []
    for dp, dn, fn in os.walk(ROOT):
        dn[:] = sorted(x for x in dn if x not in SKIP_DIRS and not (Path(dp) == ROOT and x == "scripts"))
        out += [Path(dp) / f for f in sorted(fn) if f.startswith("smoke") and f.endswith(".py")]
    return out


def write_if_changed(path: Path, content: str, check: bool, changes: list[str]) -> None:
    old = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
    if old != content:
        changes.append(path.relative_to(ROOT).as_posix())
        if not check:
            path.write_text(content, encoding="utf-8", newline="\n")


def sync(check: bool) -> list[str]:
    changes: list[str] = []
    for d in projects():
        write_if_changed(d / "pyproject.toml", render_pyproject(d), check, changes)
        deps, rp = read_requirements(d / "requirements.txt"), existing_requires_python(d / "pyproject.toml")
        for s in scripts_of(d):
            text = s.read_text(encoding="utf-8")
            write_if_changed(s, with_header(text, header_block(deps, rp)), check, changes)
    for rel in STDLIB_SCRIPTS:
        s = ROOT / rel
        if s.exists():
            write_if_changed(s, with_header(s.read_text(encoding="utf-8"), header_block([], TOOLS_REQUIRES_PYTHON)), check, changes)
    for s in smoke_files():
        write_if_changed(s, with_header(s.read_text(encoding="utf-8"), header_block([], TOOLS_REQUIRES_PYTHON)), check, changes)
    return changes


def add(dir_arg: str) -> None:
    d = (ROOT / dir_arg).resolve()
    if not (d / "requirements.txt").exists():
        raise SystemExit(f"{dir_arg}: no requirements.txt")
    pp = d / "pyproject.toml"
    if pp.exists() and MARKER.split(".")[0] not in pp.read_text(encoding="utf-8")[:200]:
        raise SystemExit(f"{pp} exists and was not generated by this tool; refusing to overwrite")
    pp.write_text(render_pyproject(d), encoding="utf-8", newline="\n")
    print(f"registered {d.relative_to(ROOT).as_posix()}")


def main(argv: list[str]) -> int:
    if "--add" in argv:
        add(argv[argv.index("--add") + 1])
    if "--list" in argv:
        for d in projects():
            print(d.relative_to(ROOT).as_posix())
        return 0
    check = "--check" in argv
    changes = sync(check)
    if check:
        for c in changes:
            print(f"out of date: {c}  (run: python scripts/sync_uv.py)")
        return 1 if changes else 0
    print(f"updated {len(changes)} file(s)" if changes else "already up to date")
    if "--lock" in argv:
        for d in projects():
            print(f"uv lock: {d.relative_to(ROOT).as_posix()}", flush=True)
            r = subprocess.run(["uv", "lock"], cwd=d)
            if r.returncode:
                return r.returncode
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
